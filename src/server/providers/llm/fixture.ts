import { extractInput } from "../../ai/prompts";
import type { ChatMessage } from "./index";

/**
 * Deterministic fixture responses used ONLY by automated tests
 * (LLM_PROVIDER=fixture + ALLOW_FIXTURE_PROVIDERS=true, refused in production).
 * They exercise the full pipeline (schemas, evidence verification, storage)
 * without network calls. Results produced this way are labelled FIXTURE.
 */
type AssessInput = {
  competencies: { key: string }[];
  answers: { position: number; question: string; answer: string }[];
};

function firstWords(s: string, n: number) {
  return s.split(/\s+/).filter(Boolean).slice(0, n).join(" ");
}

export function fixtureJson(purpose: string, user: string): unknown {
  const input = extractInput<Record<string, unknown>>(user);
  const base = purpose.split(".")[0];
  switch (base) {
    case "jd":
      return {
        description: `Fixture description for ${String(input.title ?? "the role")}.`,
        responsibilities: ["Deliver role responsibilities"],
        requiredQualifications: ["Relevant qualification"],
        requiredSkills: ["Communication"],
        preferredSkills: ["Teamwork"],
        inclusiveLanguageNotes: ["Fixture output — not generated by a real model."],
      };
    case "qgen": {
      const comps = (input.competencies as { key: string; name: string }[]) ?? [];
      const n = Number(input.count ?? comps.length) || 1;
      return {
        questions: Array.from({ length: n }, (_, i) => {
          const c = comps[i % Math.max(1, comps.length)] ?? { key: "general", name: "General" };
          return { prompt: `Tell me about a time you demonstrated ${c.name.toLowerCase()}.`, guidance: "Situation, action, result.", competencyKey: c.key };
        }),
      };
    }
    case "turn": {
      const t = input as { remainingQuestions?: string[]; followUpsRemaining?: number; lastAnswer?: string; nextQuestion?: string | null };
      if (!t.nextQuestion) return { action: "END", say: "Thank you for your time. The hiring team will review your interview and be in touch." };
      return { action: "ASK_NEXT", say: t.nextQuestion };
    }
    case "assess": {
      const a = input as unknown as AssessInput;
      return {
        summary: "Fixture assessment generated for automated testing.",
        results: a.competencies.map((c, i) => {
          const ans = a.answers[i % Math.max(1, a.answers.length)];
          if (!ans || ans.answer.trim().split(/\s+/).length < 5) {
            return { competencyKey: c.key, rating: "INSUFFICIENT_EVIDENCE", explanation: "Not enough relevant content.", evidence: [], missingEvidence: "No substantive answer addressed this competency.", uncertainty: "HIGH" };
          }
          return {
            competencyKey: c.key,
            rating: "R3",
            explanation: "The answer describes a relevant situation and actions.",
            evidence: [{ excerpt: firstWords(ans.answer, 8), answerPosition: ans.position, supports: "POSITIVE" }],
            missingEvidence: "",
            uncertainty: "MEDIUM",
          };
        }),
      };
    }
    case "resume": {
      const text = String((input as { text?: string }).text ?? "");
      const email = text.match(/[\w.+-]+@[\w-]+\.[\w.]+/)?.[0] ?? null;
      return {
        name: text.split("\n")[0]?.trim() || null,
        email,
        phone: null,
        location: null,
        headline: null,
        skills: [],
        education: [],
        experience: [],
        certifications: [],
        languages: [],
        uncertainFields: ["phone", "location"],
      };
    }
    case "practiceq": {
      const n = Number((input as { count?: number }).count ?? 3);
      return { questions: Array.from({ length: n }, (_, i) => `Practice question ${i + 1} for ${String((input as { role?: string }).role ?? "the role")}: describe a relevant experience.`) };
    }
    case "practicefb": {
      const answers = ((input as { answers?: { position: number }[] }).answers ?? []) as { position: number }[];
      return {
        summary: "Fixture coaching feedback.",
        strengths: ["Answered every question"],
        improvements: ["Add a concrete result to each example"],
        perQuestion: answers.map((a) => ({ position: a.position, relevance: "MEDIUM", clarity: "MEDIUM", completeness: "MEDIUM", suggestions: ["State the outcome"], exampleStructure: "Situation → Task → Action → Result" })),
      };
    }
    default:
      throw new Error(`No fixture for purpose ${purpose}`);
  }
}

export function fixtureText(purpose: string, messages: ChatMessage[]): string {
  return `Fixture response (${purpose}) to: ${messages.at(-1)?.content.slice(0, 40) ?? ""}`;
}
